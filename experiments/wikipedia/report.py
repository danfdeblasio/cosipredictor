"""Write reports/wikipedia.md from results.json, hideseek.json and the blind review files (#25).

Only numbers go in the report: no article text, no review descriptions and no ISMB content.

    python experiments/wikipedia/report.py --model model.joblib
"""
import argparse
import csv
import datetime
import json
import os
import platform
import sys

import numpy
import pandas
import sklearn

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wikidata as wd  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
REVIEW_DIR = os.path.join(HERE, "review")
LABEL = "is_compbio (yes/no/unsure)"
TOOLS = [("Wikipedia classifier", "rank_ours", "Step-1 classifier (more data)"), ("Dan", "rank_dan", "Dan's tool (top COSI score)")]
BANDS = [("1-10", 1, 10), ("11-25", 11, 25), ("26-50", 26, 50)]
AGENT_SET = "44, 46, 62, 68, 79, 96 and 98"


def read_csv(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _count(labels):
    return {k: sum(1 for x in labels if x == k) for k in ("yes", "unsure", "no")}


def review_counts(sheet, key):
    """Per tool: labels in its top 50, by rank band, and biographies proposed / labelled yes."""
    label = {r["id"]: r[LABEL].strip().lower() for r in sheet}
    out = {}
    for tool, rank_col, _ in TOOLS:
        rows = [(int(r[rank_col]), label[r["id"]], r["bio"] == "True") for r in key
                if r["found_by"] in (tool, "Both")]
        out[tool] = {"top50": _count([lab for rank, lab, _ in rows if rank <= 50]),
                     "bands": {b: _count([lab for rank, lab, _ in rows if lo <= rank <= hi]) for b, lo, hi in BANDS},
                     "bio_proposed": sum(bio for _, _, bio in rows),
                     "bio_yes": sum(bio and lab == "yes" for _, lab, bio in rows)}
    out["both"] = sum(r["found_by"] == "Both" for r in key)
    return out


def _fmt(v):
    if v is None:
        return "–"
    if isinstance(v, float):
        return f"{v:.3f}".rstrip("0").rstrip(".") if not v.is_integer() else str(int(v))
    return str(v)


def table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(_fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def build_report(ev, hs, sheet, key, meta):
    rv = review_counts(sheet, key)
    versions = ", ".join(f"{k} {v}" for k, v in meta["versions"].items())
    s = ["# Finding missing Wikipedia CompBio articles", "",
         f"Wikipedia fetched {meta['fetch_date']}. COSI model: `{meta['model']}`. {versions}.", "",
         "Generated by `experiments/wikipedia/report.py` from `cache/wikipedia/results.json`, "
         "`cache/wikipedia/hideseek.json` and `experiments/wikipedia/review/`. Rerun the scripts in "
         "`experiments/wikipedia/` to rebuild it.", ""]

    n = ev["n"]
    s += ["## Step 1: CompBio or not", "",
          f"Labelled sample: {n.get('CompBio', 0)} WikiProject Computational Biology articles against "
          f"{n.get('Near field', 0)} nearby-field, {n.get('Random', 0)} random and {n.get('Lonnie examples', 0)} "
          "everyday articles. AUC (1 = perfect separation, 0.5 = chance). Learned methods use 5-fold "
          "cross-validation, seed 2026.", "",
          table(["Method", "All controls", "Everyday", "Random", "Nearby fields", "No biographies"],
                [[r["method"], r["all"], r["Lonnie examples"], r["Random"], r["Near field"], r["no biographies"]]
                 for r in ev["stage1"]]), "",
          "### Minimum lead length", "",
          table(["Min. characters", "CompBio kept", "Others kept", "Dan's tool", "Text only", "Step-1 classifier"],
                [[r["min_chars"], r["kept_compbio"], r["kept_other"], r["auc_dan"], r["auc_text_only"],
                  r["auc_text_clf"]] for r in ev["length_filter"]]), "",
          "### Biographies", "",
          table(["", "Dan's tool (median top score)", "Step-1 classifier (median)"],
                [[f"CompBio biographies (n = {ev['bio']['compbio_bio_n']})", ev["bio"]["median_top_bio"],
                  ev["bio"]["median_text_bio"]],
                 ["Other CompBio articles", ev["bio"]["median_top_nonbio"], ev["bio"]["median_text_nonbio"]]]), ""]

    s += ["## Hide-and-seek", "",
          f"{hs['n_hidden']} collection articles not used for training are hidden among {hs['n_pool']} candidates. "
          "The more-data classifier uses 2-fold cross-fitting; its row is the mean of the two folds.", "",
          table(["Method", "AUC", "Hidden in top 100", "Top 500", "Top 1000", "Recall top 1%", "Top 5%", "Top 10%"],
                [[k, m["auc"], m["hidden_in_top100"], m["hidden_in_top500"], m["hidden_in_top1000"],
                  m["recall_top1pct"], m["recall_top5pct"], m["recall_top10pct"]] for k, m in hs["methods"].items()]),
          "", "### Median percentile of hidden articles", "",
          table(["Class", "n", "Step-1 (labelled only)", "Step-1 (more data)", "Dan's tool"],
                [[r["cls"], r["n"], r["proto"], r["more"], r["dan"]] for r in hs["by_class"]]
                + [[f"Biographies", hs["bio"]["n"], hs["bio"]["proto"], hs["bio"]["more"], hs["bio"]["dan"]]]), ""]

    s += ["## Blind review", "",
          f"The top 50 candidates of each tool (biographies kept), shuffled with the tool hidden and labelled by one "
          f"annotator. {rv['both']} article appears in both lists.", "",
          table(["Tool", "Yes", "Unsure", "No", "Biographies proposed", "Biographies labelled yes"],
                [[name, rv[t]["top50"]["yes"], rv[t]["top50"]["unsure"], rv[t]["top50"]["no"], rv[t]["bio_proposed"],
                  rv[t]["bio_yes"]] for t, _, name in TOOLS]), "",
          "### By rank band (yes / unsure / no)", "",
          table(["Tool"] + [b for b, _, _ in BANDS],
                [[name] + ["{yes} / {unsure} / {no}".format(**rv[t]["bands"][b]) for b, _, _ in BANDS]
                 for t, _, name in TOOLS]), ""]

    s += ["## Quality", "",
          "Spearman correlation with the WikiProject quality class (Stub = 1 … GA = 5), CompBio articles of the "
          "labelled sample.", "",
          table(["Measure", "Spearman", "p"], [[r["measure"], r["spearman"],
                                                None if r["p"] is None else f"{r['p']:.2g}"] for r in ev["stage2"]]),
          "", table(["Class", "n", "Median top score", "Text-only top score", "Lead characters", "Page bytes"],
                    [[r["cls"], r["n"], r["top"], r["top_abs"], r["chars"], r["bytes"]] for r in ev["stage2_by_class"]]),
          ""]

    s += ["## Caveats", "",
          "- One annotator labelled the review sheet; a second annotator is recommended.",
          "- Labels for articles 21–30 were first drafted with another AI assistant and then checked by the annotator.",
          f"- Labels for articles {AGENT_SET} were set by the agent from the annotator's description, under the "
          "agreed rules.",
          "- The hide-and-seek pool counts every candidate outside the collection as not CompBio; some are, so the "
          "metrics are a lower bound.",
          "- `list=random` cannot be seeded: the random controls are the titles stored in `sets.json`.", ""]
    return "\n".join(s)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache", default=wd.DEFAULT_CACHE)
    ap.add_argument("--model", default="model.joblib", help="COSI model used by evaluate.py and hideseek.py")
    ap.add_argument("--fetch-date", help="date Wikipedia was fetched (default: date of articles.jsonl)")
    ap.add_argument("--out", default=os.path.join("reports", "wikipedia.md"))
    args = ap.parse_args(argv)
    ev = json.load(open(os.path.join(args.cache, "results.json")))
    hs = json.load(open(os.path.join(args.cache, "hideseek.json")))
    sheet = read_csv(os.path.join(REVIEW_DIR, "review_sheet.csv"))
    key = read_csv(os.path.join(REVIEW_DIR, "review_key.csv"))
    fetched = args.fetch_date or datetime.date.fromtimestamp(
        os.path.getmtime(os.path.join(args.cache, "articles.jsonl"))).isoformat()
    meta = {"fetch_date": fetched, "model": os.path.basename(args.model),
            "versions": {"Python": platform.python_version(), "scikit-learn": sklearn.__version__,
                         "pandas": pandas.__version__, "NumPy": numpy.__version__}}
    os.makedirs(os.path.dirname(args.out) or ".", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(build_report(ev, hs, sheet, key, meta))
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
